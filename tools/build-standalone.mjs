// Builds index.html: a single self-contained file (CSS + JS + Three.js inlined)
// that works by double-click (file://), on any static host and on GitHub Pages.
// Usage: npm install && npm run build
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const r = (p) => path.join(root, p);

const js = await build({
  entryPoints: [r('js/main.js')],
  bundle: true,
  format: 'iife',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  write: false,
  alias: { three: r('vendor/three/three.module.js') },
  plugins: [{
    name: 'three-addons',
    setup(b) {
      b.onResolve({ filter: /^three\/addons\// }, (a) => ({ path: r('vendor/three/addons/' + a.path.slice('three/addons/'.length)) }));
    },
  }],
});
const code = js.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const css = readFileSync(r('css/style.css'), 'utf8');

let html = readFileSync(r('dev.html'), 'utf8');
const swap = (from, to) => {
  if (!html.includes(from)) throw new Error('build: marker not found: ' + from.slice(0, 60));
  html = html.replace(from, () => to);
};
swap('<link rel="stylesheet" href="css/style.css" />', `<style>\n${css}\n</style>`);
html = html.replace(/\s*<script type="importmap">[\s\S]*?<\/script>/, '');
html = html.replace(/\s*<script>\s*\/\/ dev\.html loads ES modules[\s\S]*?<\/script>/, '');
swap('<script type="module" src="js/main.js"></script>', `<script>\n${code}\n</script>`);
html = html.replace('<head>', '<head>\n  <!-- Generated by tools/build-standalone.mjs from dev.html. Edit the sources, not this file. -->');

writeFileSync(r('index.html'), html);
console.log(`index.html: ${(html.length / 1024).toFixed(0)} KB`);
